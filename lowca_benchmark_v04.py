#!/usr/bin/env python3
"""Łowca Błędów v0.4 - 100-case price-classification benchmark."""

from decimal import Decimal
from lowca_engine_v03 import classify_price_change

CASES = []

# 40 normal: modest discounts and unchanged prices.
normal_pairs = [
    ("999","899"),("999","849"),("999","799"),("1299","1099"),
    ("1599","1399"),("1999","1699"),("1999","1499"),("2369","1999"),
    ("2999","2699"),("2999","2399"),("3499","2999"),("3999","3499"),
    ("4499","3999"),("4999","4499"),("5499","4999"),("5999","5399"),
    ("6499","5799"),("6999","6299"),("7499","6999"),("7999","7499"),
    ("8499","7999"),("8999","7999"),("9999","8999"),("10999","9999"),
    ("11999","10999"),("12999","11999"),("13999","12499"),("14999","12999"),
    ("15999","14999"),("16999","14999"),("17999","15999"),("18999","16999"),
    ("19999","17999"),("799","699"),("899","799"),("1099","999"),
    ("7999","7999"),("2369","2369"),("1999","1899"),("4999","4799"),
]
for old, new in normal_pairs:
    CASES.append((old, new, "NORMAL"))

# 30 large drops without structural proof of a typo.
watch_pairs = [
    ("999","699"),("999","599"),("1299","799"),("1599","899"),
    ("1999","999"),("2369","999"),("2999","1499"),("3499","1799"),
    ("3999","1999"),("4499","2299"),("4999","2499"),("5499","2699"),
    ("5999","2999"),("6499","3199"),("6999","3499"),("7499","3799"),
    ("7999","3999"),("8499","4199"),("8999","4499"),("9999","4999"),
    ("10999","5499"),("11999","5999"),("12999","6499"),("13999","6999"),
    ("14999","7499"),("15999","7999"),("17999","8999"),("19999","9999"),
    ("2369","1199"),("7999","899"),
]
for old, new in watch_pairs:
    CASES.append((old, new, "WATCH"))

# 30 strong structural anomalies.
critical_pairs = [
    ("7999","799"),("7999","79.99"),("7999","799.90"),
    ("999","99.90"),("999","99.9"),("1299","129.90"),
    ("1599","159.90"),("1999","199.90"),("2369","236.90"),
    ("2999","299.90"),("3499","349.90"),("3999","399.90"),
    ("4499","449.90"),("4999","499.90"),("5499","549.90"),
    ("5999","599.90"),("6499","649.90"),("6999","699.90"),
    ("7499","749.90"),("8499","849.90"),("8999","899.90"),
    ("9999","999.90"),("10999","1099.90"),("11999","1199.90"),
    ("12999","1299.90"),("13999","1399.90"),("14999","1499.90"),
    ("15999","1599.90"),("17999","1799.90"),("19999","1999.90"),
]
for old, new in critical_pairs:
    CASES.append((old, new, "CRITICAL"))


def main():
    passed = 0
    failed = []

    for old, new, expected in CASES:
        result = classify_price_change(Decimal(old), Decimal(new))
        if result.level == expected:
            passed += 1
        else:
            failed.append(
                f"{old} -> {new}: expected {expected}, got {result.level}; "
                + "; ".join(result.reasons)
            )

    print("=== ŁOWCA BŁĘDÓW v0.4 — BENCHMARK ===")
    print(f"Przypadki: {len(CASES)}")
    print(f"PASS: {passed}")
    print(f"FAIL: {len(failed)}")

    if failed:
        print("\n--- BŁĘDY ---")
        for item in failed:
            print(item)
        raise SystemExit(1)

    print("\nWYNIK: 100% PASS")


if __name__ == "__main__":
    main()
